#!/usr/bin/env bun
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import {
  AI_EVAL_SUBJECTS,
  ALERT_EVALUATOR_SUBJECTS,
  ALERT_RULE_KINDS,
  ALERT_SEVERITIES,
  ALERT_STATES,
  AUTH_MODES,
  AUTH_PROVIDERS,
  COMPANY_ROLES,
  CONTRACT_GENERATION_TARGETS,
  CONTROL_PLANE_SUBJECTS,
  DEPLOYMENT_MODES,
  ORGANIZATION_INVITATION_STATUSES,
  PROJECT_MEMBER_SOURCES,
  PROJECT_ROLES,
  PROJECT_STATUSES,
  RETENTION_DATA_CLASSES,
  RETENTION_MODES,
  STORAGE_MAINTENANCE_SUBJECTS,
} from "../../apps/packages/definition/src/index.ts";

const root = process.cwd();
const checkOnly = process.argv.includes("--check");

const generatedTs = `// Generated by tooling/scripts/generate-contracts.mjs from @cloudgrid/definition.
export const DEPLOYMENT_MODES = ${inlineTsArray(DEPLOYMENT_MODES)} as const;
export const AUTH_MODES = ${inlineTsArray(AUTH_MODES)} as const;
export const AUTH_PROVIDERS = ${inlineTsArray(AUTH_PROVIDERS)} as const;
export const COMPANY_ROLES = ${inlineTsArray(COMPANY_ROLES)} as const;
export const ORGANIZATION_INVITATION_STATUSES = ${multilineTsArray(ORGANIZATION_INVITATION_STATUSES)} as const;
export const PROJECT_ROLES = ${inlineTsArray(PROJECT_ROLES)} as const;
export const PROJECT_MEMBER_SOURCES = ${inlineTsArray(PROJECT_MEMBER_SOURCES)} as const;
export const PROJECT_STATUSES = ${inlineTsArray(PROJECT_STATUSES)} as const;
export const RETENTION_DATA_CLASSES = ${multilineTsArray(RETENTION_DATA_CLASSES)} as const;
export const RETENTION_MODES = ${inlineTsArray(RETENTION_MODES)} as const;
export const ALERT_RULE_KINDS = ${multilineTsArray(ALERT_RULE_KINDS)} as const;
export const ALERT_SEVERITIES = ${inlineTsArray(ALERT_SEVERITIES)} as const;
export const ALERT_STATES = ${inlineTsArray(ALERT_STATES)} as const;
export const CONTROL_PLANE_SUBJECTS = ${multilineTsArray(CONTROL_PLANE_SUBJECTS)} as const;
export const STORAGE_MAINTENANCE_SUBJECTS = ${multilineTsArray(STORAGE_MAINTENANCE_SUBJECTS)} as const;
export const ALERT_EVALUATOR_SUBJECTS = ${multilineTsArray(ALERT_EVALUATOR_SUBJECTS)} as const;
export const AI_EVAL_SUBJECTS = ${multilineTsArray(AI_EVAL_SUBJECTS)} as const;
export const CONTRACT_GENERATION_TARGETS = ${multilineTsArray(CONTRACT_GENERATION_TARGETS)} as const;
`;

const generatedGo = `// Code generated by tooling/scripts/generate-contracts.mjs from @cloudgrid/definition; DO NOT EDIT.
package contracts

var DeploymentModes = []string{${DEPLOYMENT_MODES.map(quoteGo).join(", ")}}
var AuthModes = []string{${AUTH_MODES.map(quoteGo).join(", ")}}
var AuthProviders = []string{${AUTH_PROVIDERS.map(quoteGo).join(", ")}}
var CompanyRoles = []string{${COMPANY_ROLES.map(quoteGo).join(", ")}}
var OrganizationInvitationStatuses = []string{${ORGANIZATION_INVITATION_STATUSES.map(quoteGo).join(", ")}}
var ProjectRoles = []string{${PROJECT_ROLES.map(quoteGo).join(", ")}}
var ProjectMemberSources = []string{${PROJECT_MEMBER_SOURCES.map(quoteGo).join(", ")}}
var ProjectStatuses = []string{${PROJECT_STATUSES.map(quoteGo).join(", ")}}
var RetentionDataClasses = []string{${RETENTION_DATA_CLASSES.map(quoteGo).join(", ")}}
var RetentionModes = []string{${RETENTION_MODES.map(quoteGo).join(", ")}}
var AlertRuleKinds = []string{${ALERT_RULE_KINDS.map(quoteGo).join(", ")}}
var AlertSeverities = []string{${ALERT_SEVERITIES.map(quoteGo).join(", ")}}
var AlertStates = []string{${ALERT_STATES.map(quoteGo).join(", ")}}
var ControlPlaneSubjects = []string{${CONTROL_PLANE_SUBJECTS.map(quoteGo).join(", ")}}
var StorageMaintenanceSubjects = []string{${STORAGE_MAINTENANCE_SUBJECTS.map(quoteGo).join(", ")}}
var AlertEvaluatorSubjects = []string{${ALERT_EVALUATOR_SUBJECTS.map(quoteGo).join(", ")}}
var AiEvalSubjects = []string{${AI_EVAL_SUBJECTS.map(quoteGo).join(", ")}}
`;

const targets = [
  ["apps/packages/ui-contracts/src/generated.ts", generatedTs],
  ["core/go-contracts/generated_contracts.go", generatedGo],
];

let drifted = false;
for (const [file, content] of targets) {
  const path = join(root, file);
  const existing = await readFile(path, "utf8").catch(() => "");
  if (existing !== content) {
    drifted = true;
    if (!checkOnly) {
      await writeFile(path, content);
    }
  }
}

if (checkOnly && drifted) {
  throw new Error("generated contract outputs are stale; run bun run contracts:generate");
}

console.log(
  checkOnly ? "generated contracts are deterministic" : "generated contract metadata written",
);

function quoteGo(value) {
  return JSON.stringify(value);
}

function inlineTsArray(values) {
  return `[${values.map((value) => JSON.stringify(value)).join(", ")}]`;
}

function multilineTsArray(values) {
  return `[\n${values.map((value) => `  ${JSON.stringify(value)},`).join("\n")}\n]`;
}
